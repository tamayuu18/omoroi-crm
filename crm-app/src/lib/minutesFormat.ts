/** 新フォーマットの先頭見出し。履歴本文がこれで始まっていれば新フォーマットとみなす */
export const MINUTES_FIRST_HEADING = '## 面談概要'

/** 議事録の雛形（markdown）。AIにはこの見出し構成をそのまま使わせる */
export const MINUTES_TEMPLATE = `## 面談概要
- 面談日時: （ファイル名や本文から分かる範囲で）
- 面談種別: 初回面談 / 2回目以降 / 状況確認 / 面接対策 / 内定後フォロー / その他
- 参加者: CA ○○ ／ 求職者 ○○様
- 所要時間: （分かれば）

## 求職者の現状
- 現職・経歴（会社名、職種、在籍年数、担当業務、現年収）
- 転職理由・きっかけ（本人の言葉に近い形で、背景まで）
- 転職活動の状況（他エージェントの利用、応募中・選考中の企業、内定の有無）

## 希望条件
- 職種・業界
- 勤務地・働き方（リモート可否、残業、転勤、勤務時間）
- 年収（現在 / 最低ライン / 希望）
- 入社可能時期
- 譲れない条件と優先順位
- 避けたい条件

## 面談内容（詳細）
### （話題ごとに小見出しを付ける）
- 話した内容を時系列で、具体的に書く（数字・固有名詞・理由・背景を省略しない）
- 求職者の発言は「求職者:」、CAの説明や提案は「CA:」と区別する

## 紹介・提案した求人／企業
- 企業名・ポジション・求職者の反応（興味あり / 保留 / 辞退）とその理由

## 決定事項・合意事項
- 面談の中で決まったこと、双方で合意したこと

## ToDo
### CA側
- [ ] 内容（期限: YYYY-MM-DD）
### 求職者側
- [ ] 内容（期限: YYYY-MM-DD）

## 懸念・特記事項
- 懸念点、配慮が必要な事情（家庭・健康・退職交渉の状況など）、温度感

## 次回予定
- 次回の面談・連絡の予定（日時・方法・内容）`

/** 書き方のルール。プロンプトにそのまま載せる */
export const MINUTES_RULES = [
  '「要約」ではなく「記録」を作る。面談に同席していない人が読んでも、話の流れと中身を再現できる詳しさで書く。',
  '分量の目安は、面談1時間あたり2,000〜4,000字。1,000字を下回る場合は情報を落としていないか見直す。',
  '数字（年収、年齢、年数、件数、日付、時間）、固有名詞（企業名、職種、資格、ツール名、人名）、理由・背景は必ず残す。',
  '箇条書きは1項目1事実。「〜について話した」「〜を確認した」のような中身のない表現は禁止。何をどう話したかを書く。',
  '推測で補わない。本文に無いことは書かない。聞き取れない・不明な点は「（不明）」と書く。',
  '該当する内容が無い見出しは「特になし」と書き、見出し自体は削除しない。見出しの名称と順番は雛形どおりにする。',
  '話者は「求職者」「CA」で区別する。CAの発言と求職者の発言を混ぜない。',
  '文体は「です・ます」を使わない常体（〜した、〜とのこと）。敬称は求職者に「様」を付ける。',
] as const

/** 履歴本文が新フォーマット（詳細議事録）で書かれているか */
export function isDetailedMinutes(content: string): boolean {
  return (content || '').trimStart().startsWith(MINUTES_FIRST_HEADING)
}
